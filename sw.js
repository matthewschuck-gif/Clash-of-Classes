// Clean-up worker: the old site cached itself for offline use, so returning visitors would
// keep seeing the old page. This version deletes those caches, unregisters itself and reloads
// open tabs onto the new site. At cutover this file becomes the repo's sw.js.
self.addEventListener('install', function () { self.skipWaiting(); });
self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys()
      .then(function (keys) { return Promise.all(keys.map(function (k) { return caches.delete(k); })); })
      .then(function () { return self.registration.unregister(); })
      .then(function () { return self.clients.matchAll({ type: 'window' }); })
      .then(function (clients) { clients.forEach(function (c) { c.navigate(c.url); }); })
  );
});
